func openHostedTestRuntime(t *testing.T) *Runtime {
	t.Helper()
	rt, err := Open(t.Context(), Config{Profile: ProfileHosted, DataDir: t.TempDir(), AutoMigrate: true,
		ListenAddr: "0.0.0.0:8080", LaunchToken: "caller-supplied-token"})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		if err := rt.Close(context.Background()); err != nil {
			t.Error(err)
		}
	})
	return rt
}

func hostedRequest(rt *Runtime, owner, method, path, body string, headers map[string]string) *httptest.ResponseRecorder {
	req := httptest.NewRequest(method, "https://team.example/api"+path, strings.NewReader(body))
	req.RemoteAddr = "203.0.113.42:12345"
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Origin", "https://team.example")
	for key, value := range headers {
		req.Header.Set(key, value)
	}
	if owner != "" {
		req = req.WithContext(workspace.WithAuthenticatedOwner(req.Context(), owner))
	}
	w := httptest.NewRecorder()
	rt.GatewayHandler().ServeHTTP(w, req)
	return w
}

func requireHostedStatus(t *testing.T, w *httptest.ResponseRecorder, status int) {
	t.Helper()
	if w.Code != status {
		t.Fatalf("status = %d, want %d: %s", w.Code, status, w.Body.String())
	}
	if status == http.StatusUnauthorized {
		var envelope map[string]any
		if json.Unmarshal(w.Body.Bytes(), &envelope) != nil || envelope["code"] != float64(401) || envelope["reason"] != "unauthorized" || envelope["msg"] == "" {
			t.Fatalf("invalid unauthorized envelope: %s", w.Body.String())
		}
		if data, exists := envelope["data"]; !exists || data != nil {
			t.Fatal("unauthorized envelope must include data:null")
		}
	}
}

func TestHostedGatewayTrustAndWorkspaceIsolation(t *testing.T) {
	t.Setenv("BEEFTV_UI_BOOTSTRAP", "1")
	t.Setenv("BEEFTV_AGENT_HOST_TOKEN", "shared-environment-host")
	a, b := openHostedTestRuntime(t), openHostedTestRuntime(t)
	if a.WorkspaceID() == b.WorkspaceID() || a.LaunchToken() == b.LaunchToken() || len(a.LaunchToken()) != 64 || a.LaunchToken() == "caller-supplied-token" {
		t.Fatal("hosted runtimes must have independent identities and random launch credentials")
	}
	hostTokens := make(map[*Runtime]string)
	for _, rt := range []*Runtime{a, b} {
		rt.assistantHost.TestingUseOwnedEndpoint("http://127.0.0.1:1", "test-instance", "")
		req, err := rt.assistantHost.NewChildRequest(t.Context(), "GET", "/api/ops", nil)
		if err != nil {
			t.Fatal(err)
		}
		hostTokens[rt] = req.Header.Get("X-Beeftv-Agent-Token")
		if len(hostTokens[rt]) != 64 || hostTokens[rt] == "shared-environment-host" {
			t.Fatal("host credential must be generated by this kernel")
		}
		req.Header.Set("X-Desktop-Token", rt.LaunchToken())
		req.RemoteAddr = "203.0.113.42:12345"
		w := httptest.NewRecorder()
		rt.callbackHandler.ServeHTTP(w, req)
		requireHostedStatus(t, w, 200)
		w = httptest.NewRecorder()
		rt.GatewayHandler().ServeHTTP(w, req)
		requireHostedStatus(t, w, 401)
	}
	if hostTokens[a] == hostTokens[b] {
		t.Fatal("host credentials must not be shared between kernels")
	}
	crossCallback := httptest.NewRequest("GET", "/api/ops", nil)
	crossCallback.Header.Set("X-Desktop-Token", a.LaunchToken())
	crossCallback.Header.Set("X-Beeftv-Agent-Token", hostTokens[a])
	w := httptest.NewRecorder()
	b.callbackHandler.ServeHTTP(w, crossCallback)
	requireHostedStatus(t, w, 401)
	ownerToken, err := agentops.EnsureOwnerToken(a.cfg.DataDir)
	if err != nil {
		t.Fatal(err)
	}
	client, credential, err := agentops.NewClientRegistry(a.cfg.DataDir).Register("hosted-test", agentops.ClientReadWrite)
	if err != nil {
		t.Fatal(err)
	}
	for _, headers := range []map[string]string{
		nil,
		{"X-Beeftv-Owner": ownerToken},
		{"X-Desktop-Token": a.LaunchToken(), "X-Beeftv-UI-Bootstrap": "ui"},
		{"X-Beeftv-Client": client.ID, "Authorization": "Bearer " + credential},
		{"X-Beeftv-Agent-Token": "shared-environment-host", "X-Desktop-Token": a.LaunchToken()},
		{"X-Beeftv-Agent-Token": hostTokens[a], "X-Desktop-Token": a.LaunchToken()},
		{"Cookie": "X-Beeftv-Owner=" + ownerToken, "X-Forwarded-For": "127.0.0.1"},
	} {
		for _, route := range []struct{ method, path string }{
			{"GET", "/projects"}, {"GET", "/canvas-projects"},
			{"POST", "/ops/canvas.document.commit"}, {"POST", "/assistant/ui-session"},
			{"POST", "/creation-runs"},
		} {
			requireHostedStatus(t, hostedRequest(a, "", route.method, route.path, `{}`, headers), 401)
			req := httptest.NewRequest(route.method, "http://127.0.0.1:12345/api"+route.path+"?owner="+ownerToken, strings.NewReader(`{}`))
			req.RemoteAddr = "127.0.0.1:12346"
			for key, value := range headers {
				req.Header.Set(key, value)
			}
			w := httptest.NewRecorder()
			a.GatewayHandler().ServeHTTP(w, req)
			requireHostedStatus(t, w, 401)
		}
	}
	fixtures := []struct {
		rt    *Runtime
		title string
	}{{a, "only-A"}, {b, "only-B"}}
	for _, fixture := range fixtures {
		rt, title := fixture.rt, fixture.title
		requireHostedStatus(t, hostedRequest(rt, rt.WorkspaceID(), "POST", "/projects", `{"name":"`+title+`"}`, nil), 200)
		requireHostedStatus(t, hostedRequest(rt, rt.WorkspaceID(), "PUT", "/canvas-projects/shared-id",
			`{"project":{"id":"shared-id","revision":0,"title":"initial","nodes":[],"connections":[]}}`, nil), 200)
		requireHostedStatus(t, hostedRequest(rt, rt.WorkspaceID(), "POST", "/ops/canvas.document.commit",
			`{"opId":"save-1","params":{"canvasId":"shared-id","expectedRevision":1,"document":{"title":"`+title+`","nodes":[],"connections":[]}}}`, nil), 200)
		requireHostedStatus(t, hostedRequest(rt, rt.WorkspaceID(), "POST", "/assistant/ui-session", `{}`, nil), 200)
		requireHostedStatus(t, hostedRequest(rt, rt.WorkspaceID(), "POST", "/creation-runs", `{"clientKey":"page-1","state":{}}`, nil), 200)
	}
	for _, fixture := range fixtures {
		rt, title := fixture.rt, fixture.title
		for _, path := range []string{"/projects", "/canvas-projects", "/canvas-projects/shared-id"} {
			w := hostedRequest(rt, rt.WorkspaceID(), "GET", path, "", nil)
			requireHostedStatus(t, w, 200)
			if !strings.Contains(w.Body.String(), title) || strings.Contains(w.Body.String(), map[string]string{"only-A": "only-B", "only-B": "only-A"}[title]) {
				t.Fatalf("workspace data crossed at %s: %s", path, w.Body.String())
			}
		}
	}
	for _, path := range []string{"/projects", "/canvas-projects/shared-id"} {
		requireHostedStatus(t, hostedRequest(b, a.WorkspaceID(), "GET", path, "", nil), 401)
	}
	requireHostedStatus(t, hostedRequest(b, a.WorkspaceID(), "POST", "/ops/canvas.document.commit", `{}`, nil), 401)
}

func TestHostedWorkspaceLock(t *testing.T) {
	rt := openHostedTestRuntime(t)
	duplicate, err := Open(t.Context(), rt.cfg)
	if err == nil {
		_ = duplicate.Close(context.Background())
		t.Fatal("the same workspace was opened twice")
	}
	if rt.listener != nil || rt.BaseURL() != "" {
		t.Fatal("Open must not start a listener")
	}
	if err := rt.Close(context.Background()); err != nil {
		t.Fatal(err)
	}
	reopened, err := Open(t.Context(), rt.cfg)
	if err != nil {
		t.Fatalf("workspace lock not released: %v", err)
	}
	if err := reopened.Close(context.Background()); err != nil {
		t.Fatal(err)
	}
}

func TestHostedListenerLifecycle(t *testing.T) {
	rt := openHostedTestRuntime(t)
	if err := rt.Start(); err != nil {
		t.Fatal(err)
	}
	if !rt.Ready() || rt.backgroundDone == nil || !rt.listener.Addr().(*net.TCPAddr).IP.IsLoopback() || rt.cfg.ListenAddr != "127.0.0.1:0" {
		t.Fatal("hosted Start must run workers with only a private callback listener")
	}
	w := httptest.NewRecorder()
	rt.httpServer.Handler.ServeHTTP(w, httptest.NewRequest("GET", "/api/ops", nil))
	requireHostedStatus(t, w, 401)
}
